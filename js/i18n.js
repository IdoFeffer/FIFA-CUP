export function t(key, params = {}) {
  const v = STRINGS[lang][key] ?? STRINGS.he[key];
  if (v === undefined) {
    console.warn('missing string', key);
    return key;
  }
  return typeof v === 'function' ? v(params) : v;
}

/** שם ברירת מחדל ("שחקן 3" / "Player 3") מוצג בשפה הפעילה. שמות שהוקלדו לא משתנים */
export function localName(name) {
  const m = /^(?:שחקן|Player) (\d+)$/.exec(name);
  return m ? t('playerN', { n: m[1] }) : name;
}

/** לבדיקות: כל המפתחות קיימים בשתי השפות */
export function missingKeys() {
  const he = Object.keys(STRINGS.he);
  const en = Object.keys(STRINGS.en);
  return { inEn: he.filter((k) => !en.includes(k)), inHe: en.filter((k) => !he.includes(k)) };
}
